export function routeGeometry(route: string | null | undefined): LusakaRoute | undefined {
  if (!route) return undefined;
  return LUSAKA_ROUTES.find((item) => item.route === route);
}

const demoPaths = new Map(LUSAKA_ROUTES.map(({ route, points }) => [
  route,
  [...points, ...points.slice(0, -1).reverse()],
]));

/** Reuse the same road back to town so demo buses never teleport at the route end. */
export function demoRoutePath(route: string | null): GeoPoint[] {
  return demoPaths.get(route ?? '') ?? [];
}
