import { test, expect } from '@playwright/test';

test('new rider tops up and opens a pending fare ticket', async ({ page }) => {
  const phone = `097${String(Date.now()).slice(-7)}`;
  await page.goto('/signup');
  await page.getByLabel('Name').fill('Test Rider');
  await page.getByLabel('Phone').fill(phone);
  await page.getByLabel('6-digit PIN', { exact: true }).fill('246810');
  await page.getByLabel('Confirm PIN', { exact: true }).fill('246810');
  await page.getByLabel('I agree to the terms').check();
  await page.getByRole('button', { name: 'Create account' }).click();
  await expect(page).toHaveURL(/\/login\?created=1$/);
  await expect(page.getByText('Account created. Sign in to continue.')).toBeVisible();
  const pin = page.getByLabel('Six-digit PIN', { exact: true });
  await page.getByLabel('Phone number').fill(phone);
  await pin.fill('246810');
  await expect(pin).toHaveAttribute('type', 'password');
  await page.getByRole('button', { name: 'Show Six-digit PIN' }).click();
  await expect(pin).toHaveAttribute('type', 'text');
  await expect(pin).toHaveValue('246810');
  await page.getByRole('button', { name: 'Hide Six-digit PIN' }).click();
  await page.getByRole('button', { name: 'Log in' }).click();
  await expect(page).toHaveURL(/\/home$/);
  await page.goto('/topup');
  await page.getByRole('button', { name: 'K20', exact: true }).click();
  await page.getByRole('button', { name: 'Review K20.00' }).click();
  await page.getByLabel('Re-enter the amount in K').fill('21');
  await page.getByRole('button', { name: 'Confirm +K20.00' }).click();
  await expect(page.getByText('That amount does not match. Check it and try again.', { exact: true })).toBeVisible();
  await page.getByLabel('Re-enter the amount in K').fill('20.00');
  await page.getByRole('button', { name: 'Confirm +K20.00' }).click();
  await expect(page.getByText('Simulated top-up complete')).toBeVisible({ timeout: 15000 });
  await page.goto('/home');
  await page.getByRole('link', { name: /Pay a fare/ }).click();
  await page.getByLabel('Bus number').fill('12');
  await page.locator('button').filter({ hasText: /^K\d+$/ }).first().click();
  await page.getByRole('button', { name: /Pay K/ }).click();
  await page.waitForURL('**/receipt/**');
  await expect(page.getByText('Pending · Waiting for conductor')).toBeVisible();
  await page.goto('/home');
  await page.locator('nav[aria-label="Passenger"]').getByRole('button', { name: 'Log out' }).click();
  await expect(page).toHaveURL(/\/login$/);
});

test('Fleet welcome offers registration and both sign-in paths', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 640 });
  await page.goto('/business');
  const choices = page.locator('#hero-ctas');
  await expect(choices.getByRole('link', { name: 'Sign in as Operator' })).toBeVisible();
  await expect(choices.getByRole('link', { name: 'Sign in as Conductor' })).toBeVisible();
  await choices.getByRole('link', { name: 'Create an operator account' }).click();
  await page.getByLabel('Your name').fill('Test Operator');
  await page.getByLabel('Company').fill('Test Fleet');
  const phone = `096${String(Date.now()).slice(-7)}`;
  await page.getByLabel('Phone').fill(phone);
  await page.getByLabel('6-digit PIN', { exact: true }).fill('246810');
  await page.getByRole('button', { name: 'Create fleet' }).click();
  await expect(page).toHaveURL(/\/business\/login\?created=1$/);
  await page.getByLabel('Phone number').fill(phone);
  await page.getByLabel('Six-digit PIN', { exact: true }).fill('246810');
  await page.getByRole('button', { name: 'Log in' }).click();
  await expect(page).toHaveURL(/\/business\/desk$/);
  await page.getByRole('button', { name: 'Open account menu' }).click();
  await page.locator('#operator-account-menu').getByRole('button', { name: 'Log out' }).click();
  await expect(page).toHaveURL(/\/business\/login$/);
  await page.getByRole('link', { name: 'Sign in as Conductor' }).click();
  await expect(page).toHaveURL(/\/business\/conductor\/login$/);
  await page.getByRole('link', { name: 'Forgot PIN?' }).click();
  await expect(page.getByRole('heading', { name: 'Reset your PIN' })).toBeVisible();
  await expect(page.getByText('Need help? Contact your bus operator.')).toBeVisible();
  await page.getByRole('link', { name: 'Back to sign in' }).click();
  await expect(page).toHaveURL(/\/business\/conductor\/login$/);
});
